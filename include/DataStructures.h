// Algorithm 1 closure-pointer representation.  A root without CLOS has an
// empty EA (plaintext NULL).  A terminal closure entry stores this fixed-size
// canonical NULL after P_2 masking, so deblinding can recognize termination
// without probing T_I with an invalid address.
inline constexpr size_t kTiProtectedAddressBytes = 16;
inline constexpr size_t kClosurePointerPayloadBytes = 8 + kTiProtectedAddressBytes;

inline const std::vector<uint8_t>& CanonicalClosureNullPayload() {
    static const std::vector<uint8_t> value(kClosurePointerPayloadBytes, 0);
    return value;
}

inline bool IsCanonicalClosureNullPayload(const std::vector<uint8_t>& value) {
    return value == CanonicalClosureNullPayload();
}

// Defines in-memory layouts for the Graph Look-up Table T_I,
// the Triplet Look-up Table T_L=(FTI, IFTI),
// the Complete Feature Bitmap Index T_CFBI,
// and graphlet-index related query structures.

// Graph Look-up Table T_I cell.
struct TICell {
    // Unkeyed DFS-code equality hash generated by DfsHash(dfs(f)).
    std::vector<uint8_t> H_dfs;

    // DFS-bound masked identifier bitmap D_f.
    std::vector<uint8_t> ED;

    // Empty means the root has plaintext NULL (no CLOS).  Otherwise this is a
    // masked counter||next-address pointer or a masked canonical NULL at the
    // final closure entry.
    std::vector<uint8_t> EA;
};

// FTI count-bucket cell in the Triplet Look-up Table T_L=(FTI, IFTI).
struct TripCell {
    // ORE ciphertext for a triplet-count bucket.
    std::vector<uint8_t> ORE_limit;

    // AES-encrypted T_I address set. The historical field name is retained
    // for compatibility with the surrounding code.
    std::vector<uint8_t> AES_addr;
};

// One FTI row, partitioned by query graph size.
struct TripRow {
    std::map<int, std::vector<TripCell>> size_slices;
};

// Hash and equality helpers for binary encrypted-index addresses.
struct VectorUint8Hash {
    size_t operator()(const std::vector<uint8_t>& v) const noexcept {
        // 64-bit FNV-1a
        uint64_t hash = 1469598103934665603ULL;
        for (uint8_t b : v) {
            hash ^= b;
            hash *= 1099511628211ULL;
        }
        return static_cast<size_t>(hash);
    }
};

struct VectorUint8Eq {
    bool operator()(const std::vector<uint8_t>& a, const std::vector<uint8_t>& b) const noexcept {
        return a == b;
    }
};

using TITableVecKey =
    std::unordered_map<std::vector<uint8_t>, TICell, VectorUint8Hash, VectorUint8Eq>;

// Complete Feature Bitmap Index T_CFBI. Each protected feature token maps to
// an at-rest masked presence bitmap over all outsourced data graph IDs.
using CompleteFeatureBitmapIndex =
    std::unordered_map<std::vector<uint8_t>, std::vector<uint8_t>,
                       VectorUint8Hash, VectorUint8Eq>;
